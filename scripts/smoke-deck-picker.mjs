import assert from 'node:assert/strict';
import { deckKey, filterSelectionDecks, selectionDecks, loadDeckFavorites, saveDeckFavorites } from '../ui/src/deckSelection.ts';
const storage = new Map();
globalThis.localStorage = { getItem: key => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, value) };
const mine = { source: 'mine', name: 'Marés', identity: 18, cards: 100, commanders: [{ name: 'Hakbal da Alma Crescente', nameEn: 'Hakbal of the Surging Soul' }] };
const precon = { source: 'precon', name: 'Marés', identity: 7, cards: 100, commanders: [{ name: 'Comandante', nameEn: 'Commander' }] };
const partner = { source: 'precon', name: 'Partners', identity: 31, commanders: [{ name: 'First', nameEn: 'First' }, { name: 'Segundo', nameEn: 'Second' }] };
const colorless = { source: 'precon', name: 'Colorless', identity: 0, commanders: [] };
const decks = [mine, precon, partner, colorless];
assert.notEqual(deckKey(mine), deckKey(precon), 'source disambiguates equal names');
const favorites = new Set([deckKey(precon)]);
assert.deepEqual(filterSelectionDecks(decks, 'MARES', 'all', -1, favorites), [mine, precon], 'accent-insensitive name search');
assert.deepEqual(filterSelectionDecks(decks, 'surging soul', 'all', -1, favorites), [mine], 'English commander search');
assert.deepEqual(filterSelectionDecks(decks, 'crescente', 'all', -1, favorites), [mine], 'translated commander search');
assert.deepEqual(filterSelectionDecks(decks, 'second', 'all', -1, favorites), [partner], 'both partners are searchable');
assert.deepEqual(filterSelectionDecks(decks, '', 'mine', -1, favorites), [mine]);
assert.deepEqual(filterSelectionDecks(decks, '', 'favorites', -1, favorites), [precon]);
assert.deepEqual(filterSelectionDecks(decks, '', 'all', 16, favorites), [mine, partner]);
assert.deepEqual(filterSelectionDecks(decks, '', 'all', 0, favorites), [colorless]);
assert.deepEqual(filterSelectionDecks(decks, 'missing', 'all', -1, favorites), []);
const lists = { mine: ['Marés'], precons: ['Marés', 'Old engine'], summaries: decks };
assert.deepEqual(selectionDecks(lists), [mine, precon, { name: 'Old engine', source: 'precon' }], 'deleted or renamed entries are not resurrected by stale summaries');
assert.deepEqual(selectionDecks({ mine: [], precons: ['Unknown'] }), [{ source: 'precon', name: 'Unknown' }], 'no invented identity or artwork without metadata');
assert.deepEqual(loadDeckFavorites(), new Set());
saveDeckFavorites(favorites); assert.deepEqual(loadDeckFavorites(), favorites, 'favorites persist with source');
storage.set('reforge.favoriteDecks', 'broken'); assert.deepEqual(loadDeckFavorites(), new Set());
storage.set('reforge.favoriteDecks', JSON.stringify(['invalid', JSON.stringify(['unknown', 'a']), deckKey(mine)]));
assert.deepEqual(loadDeckFavorites(), new Set([deckKey(mine)]));
globalThis.localStorage = { getItem() { throw Error('blocked'); }, setItem() { throw Error('blocked'); } };
assert.deepEqual(loadDeckFavorites(), new Set()); assert.doesNotThrow(() => saveDeckFavorites(favorites));
console.log('OK: deck origins, accent/commander/partner search, identity filters, stale catalogs, favorites and blocked storage');
